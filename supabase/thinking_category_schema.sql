-- 1. 테이블 생성
CREATE TABLE IF NOT EXISTS public.thinking_category (
  category_id text PRIMARY KEY,
  depth1 text NOT NULL,
  depth2 text NOT NULL,
  depth3 text NOT NULL,
  full_path text NOT NULL DEFAULT '',
  sort_order int NOT NULL DEFAULT 0,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.thinking_category IS '사고력(THK) 문항 분류 마스터 테이블';
COMMENT ON COLUMN public.thinking_category.category_id IS '사고력 분류 코드 (예: THK-01-01-01)';
COMMENT ON COLUMN public.thinking_category.depth1 IS '대분류 영역 (예: 수와 연산 감각)';
COMMENT ON COLUMN public.thinking_category.depth2 IS '중분류 주제 (예: 숨겨진 수 찾기)';
COMMENT ON COLUMN public.thinking_category.depth3 IS '소분류 유형 (예: 복면산)';
COMMENT ON COLUMN public.thinking_category.full_path IS '전체 경로 (depth1 > depth2 > depth3)';
COMMENT ON COLUMN public.thinking_category.sort_order IS '정렬 순서 (10 단위 권장 — 중간 삽입 용이)';
COMMENT ON COLUMN public.thinking_category.is_active IS '활성 여부 (폐기/숨김 시 false)';

-- 2. 조회 최적화 인덱스
CREATE INDEX IF NOT EXISTS idx_thinking_category_active_sort
  ON public.thinking_category(is_active, sort_order, category_id);
CREATE INDEX IF NOT EXISTS idx_thinking_category_depth
  ON public.thinking_category(depth1, depth2);

-- 3. full_path 자동 완성 및 updated_at 자동 갱신 트리거
-- (Table Editor에서 행 추가 시 full_path를 비워두어도 depth1 > depth2 > depth3 형태로 자동 생성)
CREATE OR REPLACE FUNCTION public.set_thinking_category_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.full_path IS NULL OR btrim(NEW.full_path) = '' THEN
    NEW.full_path := concat_ws(
      ' > ',
      NULLIF(btrim(NEW.depth1), ''),
      NULLIF(btrim(NEW.depth2), ''),
      NULLIF(btrim(NEW.depth3), '')
    );
  END IF;
  IF TG_OP = 'UPDATE' THEN
    NEW.updated_at = now();
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_thinking_category_updated_at ON public.thinking_category;
CREATE TRIGGER trg_thinking_category_updated_at
  BEFORE INSERT OR UPDATE ON public.thinking_category
  FOR EACH ROW
  EXECUTE FUNCTION public.set_thinking_category_updated_at();

-- 4. 권한 및 RLS 정책 (클라이언트 조회 허용 + 로그인 사용자 편집 허용)
ALTER TABLE public.thinking_category ENABLE ROW LEVEL SECURITY;

GRANT SELECT ON public.thinking_category TO anon, authenticated, service_role;
GRANT INSERT, UPDATE, DELETE ON public.thinking_category TO authenticated, service_role;

DROP POLICY IF EXISTS thinking_category_select_all ON public.thinking_category;
CREATE POLICY thinking_category_select_all
  ON public.thinking_category
  FOR SELECT
  TO anon, authenticated
  USING (true);

DROP POLICY IF EXISTS thinking_category_write_authenticated ON public.thinking_category;
CREATE POLICY thinking_category_write_authenticated
  ON public.thinking_category
  FOR ALL
  TO authenticated
  USING (true)
  WITH CHECK (true);

